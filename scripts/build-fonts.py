#!/usr/bin/env python3
"""Download the site's web fonts once and write them into assets/fonts/, so pages never call Google Fonts.

Run from the repo root whenever an icon is added or removed:   python scripts/build-fonts.py

- Manrope, Roboto Condensed, JetBrains Mono, Caveat, Dancing Script and Schoolbell (SIL OFL): Latin and Latin Extended only (Latin Extended has the
  macrons Maori text needs). Each is one variable-weight file per range.
- Material Symbols Outlined (Apache-2.0): cut down by Google to just the icons the site uses, found by scanning the
  pages and scripts. Without that it is a 1.1 MB file; with it, a few dozen KB.
This script talks to Google, but only here on the developer's machine. Visitors never do.

Font files are cached by browsers for a week under the same name, so a rebuilt icon font would not reach visitors who
already have the old one (new icons show up as their plain names, like "wifi"). To prevent that, the icon font and
fonts.css carry a short hash of their content in their address (fonts.css?v=ab12cd34), and this script rewrites that
address in every page and in build-faq.py. A changed font therefore always gets a new address.
"""
import hashlib
import json
import os
import re
import sys
import urllib.parse
import urllib.request

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
OUT = os.path.join(ROOT, "assets", "fonts")
UA = {"User-Agent": "Mozilla/5.0 (Windows NT 10.0; Win64; x64) AppleWebKit/537.36 (KHTML, like Gecko) Chrome/130.0 Safari/537.36"}
KEEP_SUBSETS = ("latin", "latin-ext")
FAMILIES = [
    ("Manrope", "Manrope:wght@400;500;600;700;800", "manrope", "400 800"),
    ("Roboto Condensed", "Roboto+Condensed:wght@700;800", "roboto-condensed", "700 800"),
    ("JetBrains Mono", "JetBrains+Mono:wght@400;500", "jetbrains-mono", "400 500"),
    # used by single pages (Sign PDF's typed signature, Handwriting Worksheets); the browser only fetches a file when text uses it
    ("Caveat", "Caveat:wght@500;700", "caveat", "500 700"),
    ("Dancing Script", "Dancing+Script:wght@400..700", "dancing-script", "400 700"),
    ("Schoolbell", "Schoolbell", "schoolbell", "400"),
]


def get(url):
    with urllib.request.urlopen(urllib.request.Request(url, headers=UA), timeout=60) as r:
        return r.read()


def icon_catalog():
    text = get("https://fonts.google.com/metadata/icons?key=material_symbols&incomplete=true").decode("utf-8")
    return {i["name"] for i in json.loads(text[text.index("{"):])["icons"]}


def used_icons(catalog):
    names = set()
    skip = {".git", ".claude", "node_modules", "vendor", "fonts"}
    for base, dirs, files in os.walk(ROOT):
        dirs[:] = [d for d in dirs if d not in skip]
        for f in files:
            path = os.path.join(base, f)
            if f.endswith((".html", ".js", ".mjs", ".css")):
                text = open(path, encoding="utf-8", errors="replace").read()
            else:
                continue
            # <span class="material-symbols-outlined" ...>name</span>, in pages and inside script templates
            names.update(re.findall(r'material-symbols-outlined[^>]*>\s*([a-z0-9_]+)\s*<', text))
            if not f.endswith(".html"):
                # icon names also sit in scripts as plain quoted strings ("search", icon: "tag", textContent = "dark_mode")
                names.update(re.findall(r'["\'`]([a-z][a-z0-9_]*)["\'`]', text))
    return sorted(n for n in names if n in catalog)


def css_faces(css):
    return re.findall(r"/\* ([\w-]+) \*/\s*@font-face \{(.*?)\}", css, re.S)


def stamp_pages(version):
    """Point every page (and the FAQ page template) at fonts.css and the icon font with this version."""
    link = re.compile(r"/assets/fonts/(fonts\.css|material-symbols-outlined\.woff2)(?:\?v=[0-9a-f]+)?")
    skip = {".git", ".claude", ".hallmark", "node_modules", "vendor", "fonts"}
    changed = 0
    for base, dirs, files in os.walk(ROOT):
        dirs[:] = [d for d in dirs if d not in skip]
        for f in files:
            if not (f.endswith(".html") or f == "build-faq.py"):
                continue
            path = os.path.join(base, f)
            text = open(path, encoding="utf-8", newline="").read()
            new = link.sub(lambda m: f"/assets/fonts/{m.group(1)}?v={version}", text)
            if new != text:
                open(path, "w", encoding="utf-8", newline="").write(new)
                changed += 1
    return changed


def main():
    os.makedirs(OUT, exist_ok=True)
    rules = ["/* Generated by scripts/build-fonts.py. Do not edit by hand. */"]

    for family, spec, slug, weights in FAMILIES:
        css = get(f"https://fonts.googleapis.com/css2?family={spec}&display=swap").decode("utf-8")
        done = set()
        for subset, block in css_faces(css):
            if subset not in KEEP_SUBSETS:
                continue
            url = re.search(r"url\((https[^)]+)\)", block).group(1)
            rng = re.search(r"unicode-range: ([^;]+);", block).group(1)
            fname = f"{slug}-{subset}.woff2"
            if fname not in done:
                open(os.path.join(OUT, fname), "wb").write(get(url))
                done.add(fname)
            rules.append(
                f"@font-face{{font-family:'{family}';font-style:normal;font-weight:{weights};font-display:swap;"
                f"src:url(/assets/fonts/{fname}) format('woff2');unicode-range:{rng}}}"
            )

    catalog = icon_catalog()
    icons = used_icons(catalog)
    q = urllib.parse.quote(",".join(icons), safe=",_")
    css = get(f"https://fonts.googleapis.com/css2?family=Material+Symbols+Outlined:wght@100..700&icon_names={q}&display=block").decode("utf-8")
    url = re.search(r"url\((https[^)]+)\)", css).group(1)
    data = get(url)
    open(os.path.join(OUT, "material-symbols-outlined.woff2"), "wb").write(data)
    version = hashlib.sha1(data + "".join(rules).encode("utf-8")).hexdigest()[:8]
    rules.append(
        "@font-face{font-family:'Material Symbols Outlined';font-style:normal;font-weight:100 700;font-display:block;"
        f"src:url(/assets/fonts/material-symbols-outlined.woff2?v={version}) format('woff2')}}"
    )
    open(os.path.join(OUT, "fonts.css"), "w", encoding="utf-8").write("\n".join(rules) + "\n")
    pages = stamp_pages(version)
    print(f"font version {version}, {pages} file(s) updated")
    open(os.path.join(OUT, "icons-used.txt"), "w", encoding="utf-8").write("\n".join(icons) + "\n")
    print(f"{len(icons)} icons, material-symbols-outlined.woff2 = {len(data) // 1024} KB")
    for f in sorted(os.listdir(OUT)):
        print(f"  {f:40} {os.path.getsize(os.path.join(OUT, f)) // 1024:>4} KB")


if __name__ == "__main__":
    sys.exit(main())
