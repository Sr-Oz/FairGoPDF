// baseName should already have its extension stripped; ext should not
// include the leading dot (e.g. "pdf", not ".pdf").
function brandFilename(toolSlug, baseName, ext) {
  const toolName = (window.TOOL_NAMES && window.TOOL_NAMES[toolSlug]) || toolSlug;
  const safeBase = (baseName || "file").trim() || "file";
  return `FairGoPDF-${toolName}-${safeBase}.${ext}`;
}
